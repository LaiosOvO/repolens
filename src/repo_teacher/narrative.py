from __future__ import annotations

from collections.abc import Mapping
from typing import Any


def _profile(
    *,
    question: str,
    use_when: str,
    distinguish: str,
    trigger: str,
    owner: str,
    output: str,
    consumer: str,
    runtime: tuple[str, ...],
    construction: str,
    objects: tuple[tuple[str, str], ...],
    state: tuple[tuple[str, str, str, str], ...],
    choices: tuple[tuple[str, str, str], ...],
    supported: tuple[str, ...],
    unsupported: tuple[str, ...],
    take: tuple[str, ...],
    adapt: tuple[str, ...],
    avoid: tuple[str, ...],
    verify: tuple[str, ...],
    mechanism_model: Mapping[str, Any] | None = None,
) -> dict[str, Any]:
    mechanism = dict(mechanism_model or {
        "plain_summary": "这项能力由明确的数据结构和控制步骤组成；下面分别说明存取、决策与结束条件。",
        "storage": "该能力使用上方核心对象保存当前输入、状态与输出；具体持久化介质需结合源码证据确认。",
        "write_path": "输入经运行步骤处理后写入该能力负责的状态或输出对象。",
        "read_path": "执行器从当前状态读取所需输入；没有独立查询层时直接说明为按键或字段读取。",
        "control_loop": "按上方运行步骤推进；如果不是循环，明确为一次调用完成。",
        "decision_rules": "由显式条件、配置或返回值决定下一步，不能用调用链名称代替规则。",
        "termination": "产出结果、无后续步骤或命中保护上限时结束。",
        "dynamic_behavior": "默认只允许在运行前通过配置或注册改变结构；运行中的可变范围以源码合同为准。",
        "worked_example": list(runtime[:3]),
    })
    return {
        "question": question,
        "use_when": use_when,
        "distinguish": distinguish,
        "runtime_story": {
            "trigger": trigger,
            "owner": owner,
            "output": output,
            "consumer": consumer,
            "steps": list(runtime),
        },
        "construction": {
            "explanation": construction,
            "objects": [{"name": name, "role": role} for name, role in objects],
        },
        "mechanism_model": mechanism,
        "state_flow": [
            {"stage": stage, "reads": reads, "writes": writes, "why_next": why_next}
            for stage, reads, writes, why_next in state
        ],
        "design_choices": [
            {"choice": choice, "why": why, "cost": cost}
            for choice, why, cost in choices
        ],
        "boundary": {"supported": list(supported), "unsupported": list(unsupported)},
        "reuse_plan": {
            "take": list(take),
            "adapt": list(adapt),
            "avoid": list(avoid),
            "verify": list(verify),
        },
    }



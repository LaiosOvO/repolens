def discover_human_chapter(feature: Mapping[str, Any]) -> dict[str, Any]:
    """Return a human tutorial chapter for audited Waku mechanisms.

    Entry points and symbol paths are intentionally absent from the narrative.
    The report renders them later as evidence, after the reader understands the
    product capability and its runtime contract.
    """

    tags = feature.get("technology_tags")
    if not isinstance(tags, list) or "compatibility-corpus:waku-not-curated" not in tags:
        return {}
    mechanism = next(
        (
            str(tag).split(":", 1)[1]
            for tag in tags
            if isinstance(tag, str) and tag.startswith("compatibility-mechanism:")
        ),
        "",
    )
    template = _WAKU_CHAPTERS.get(mechanism)
    if template is None:
        return {}
    return {"mechanism": mechanism, **template}
